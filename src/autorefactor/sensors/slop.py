_EMPTY_CATCH = re.compile(
    r"catch\s*\([^)]*\)\s*\{\s*\}|except\s+(\w+\s*)?:\s*(pass|continue)\b",
    re.IGNORECASE,
)
# Bound the gap between TODO/draft and Map — unbounded ``.*`` + DOTALL ReDoS's on large files.
_DRAFT_MAP = re.compile(
    r"\b(TODO|FIXME|draft)\b.{0,240}\b(Map|HashMap)\b|\bdefaultMappings\s*=\s*new\s+HashMap",
    re.IGNORECASE | re.DOTALL,
)
_DISABLED_HOOK = re.compile(
    r"//\s*@(?:PostConstruct|EventListener)\s*\n\s*(?:public\s+)?(?:void\s+)?(validate\w*|check\w*)\s*\(",
    re.IGNORECASE | re.MULTILINE,
)
_CONFIG_JAVA_PATH = re.compile(r"src/main/.+/config/", re.IGNORECASE)
_BOILER_COMMENTS = re.compile(
    r"\b(TODO|FIXME|generated by|auto[- ]?generated|copilot|chatgpt)\b",
    re.IGNORECASE,
)

_NORM_CALLER = re.compile(
    r"\b(trim|lower|normalize|Normalize|stringsTrim|ToLower|replaceSpaces)\b",
    re.IGNORECASE,
)


# Python identity helpers: keep the gap between ``def`` and ``return`` tiny.
# The old ``(?:[^\n]*\n\s*)*`` form ReDoS's on nested defs (e.g. smoke tests with
# ``def fake_*`` inside ``main``) — never use unbounded line loops here.
_PY_IDENTITY_ONELINE = re.compile(
    r"def\s+(\w+)\(\s*(\w+)\s*(?:,[^)\n]*)?\):\s*return\s+\2\b",
)
_PY_IDENTITY_SHORT = re.compile(
    r"def\s+(\w+)\(\s*(\w+)\s*(?:,[^)\n]*)?\):\s*(?:#.*)?\n"
    r"(?:[ \t]*\n){0,2}"
    r"[ \t]+return\s+\2\b",
)
_GO_IDENTITY = re.compile(
    r"func\s+(\w+)\((\w+)\s+\w+\)\s+\w+\s*\{\s*return\s+\2\s*\}",
)
# TS/JS identity helpers: (x) => x / function f(x) { return x; } — the returned
# expression must be exactly the parameter (no `x + 1` false positives).
_TS_IDENTITY_ARROW_PAREN = re.compile(
    r"(?:export\s+)?(?:const|let)\s+(\w+)\s*=\s*\(\s*(\w+)\s*[^)]*\)\s*(?::[^=\n]+)?"
    r"=>\s*(?:\{\s*return\s+\2\s*;?\s*\}|\2\s*[;,]?\s*$)",
    re.MULTILINE,
)
_TS_IDENTITY_ARROW_BARE = re.compile(
    r"(?:export\s+)?(?:const|let)\s+(\w+)\s*=\s*(\w+)\s*"
    r"=>\s*(?:\{\s*return\s+\2\s*;?\s*\}|\2\s*[;,]?\s*$)",
    re.MULTILINE,
)
_TS_IDENTITY_FUNC = re.compile(
    r"(?:export\s+)?function\s+(\w+)\s*\(\s*(\w+)\s*[^)]*\)\s*\{\s*return\s+\2\s*;?\s*\}"
)


def _identity_helpers_in_source(snippet: str, language: str) -> list[tuple[str, str]]:
    """Find helper names whose body is a bare identity return."""
    out: list[tuple[str, str]] = []
    if language == "go":
        for m in _GO_IDENTITY.finditer(snippet):
            out.append((m.group(1), m.group(2)))
    elif language in {"typescript", "tsx", "javascript"}:
        seen: set[str] = set()
        for pat in (_TS_IDENTITY_ARROW_PAREN, _TS_IDENTITY_ARROW_BARE, _TS_IDENTITY_FUNC):
            for m in pat.finditer(snippet):
                key = m.group(1)
                if key in seen:
                    continue
                seen.add(key)
                out.append((m.group(1), m.group(2)))
    elif language == "python":
        seen: set[str] = set()
        for pat in (_PY_IDENTITY_ONELINE, _PY_IDENTITY_SHORT):
            for m in pat.finditer(snippet):
                key = m.group(1)
                if key in seen:
                    continue
                seen.add(key)
                out.append((m.group(1), m.group(2)))
    return out


def _collect_identity_findings(ctx: AnalysisContext, known: set[str]) -> list[Finding]:
    findings: list[Finding] = []
    seen: set[str] = set()
    by_path: dict[tuple[str, str], list[CodeUnit]] = defaultdict(list)
    for unit in ctx.units_list():
        if unit.kind == UnitKind.FUNCTION and not is_test_path(unit.path):
            by_path[(unit.repo, unit.path)].append(unit)

    for (_repo, _path), file_units in by_path.items():
        for unit in file_units:
            snippet = unit.source_snippet or ""
            for helper, _param in _identity_helpers_in_source(snippet, unit.language):
                key = f"{unit.path}:{helper}"
                if key in seen:
                    continue
                seen.add(key)
                callers = [
                    u
                    for u in file_units
                    if helper in (u.source_snippet or "")
                    and simple_name(u.qualified_name) != helper
                ]
                norm_context = _NORM_CALLER.search(snippet) or any(
                    _NORM_CALLER.search(u.source_snippet or "") for u in file_units
                )
                if not norm_context:
                    continue
                caller_names = [simple_name(u.qualified_name) for u in callers[:3]]
                ref = caller_names[0] if caller_names else simple_name(unit.qualified_name)
                anchor = callers[0].id if callers else unit.id
                f = try_make_finding(
                    id=content_hash(f"slop:identity:{unit.repo}:{unit.path}:{helper}"),
                    goal=AnalysisGoal.SLOP,
                    sensor="slop",
                    severity=Severity.HIGH,
                    title=f"No-op helper `{helper}` breaks parity (used by `{ref}`)",
                    evidence=(
                        f"`{helper}` is an identity return while sibling languages trim/lowercase; "
                        f"caller(s): {', '.join(caller_names) or ref}."
                    ),
                    unit_ids=[anchor, unit.id][:4],
                    action_hint=SuggestedAction.DELETE_DUPLICATE,
                    score=0.87,
                    metadata={"helper": helper, "callers": caller_names},
                    known_ids=known,
                )
                if f:
                    findings.append(f)
    return findings


def _iter_src_main_java(repo: Path):
    """Yield ``*.java`` under ``src/main`` only, pruning ignored build dirs."""
    for main in repo.glob("**/src/main"):
        # Skip anything under target/build/node_modules even if named src/main.
        parts = set(main.parts)
        if parts & IGNORE_DIR_NAMES:
            continue
        for dirpath, dirnames, filenames in os.walk(main):
            dirnames[:] = [d for d in dirnames if d not in IGNORE_DIR_NAMES and not d.startswith(".")]
            for name in filenames:
                if name.endswith(".java"):
                    yield Path(dirpath) / name


def _read_text(path: Path, limit: int = 500_000) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")[:limit]
    except OSError:
        return ""


def _is_config_validator_path(rel: str) -> bool:
    norm = rel.replace("\\", "/")
    return bool(_CONFIG_JAVA_PATH.search(norm))


def _draft_map_file_key(repo: str, path: str) -> str:
    return f"{repo}:{path.replace(chr(92), '/').lstrip('./')}"


def _type_unit_for_java_file(ctx: AnalysisContext, repo: str, rel: str) -> str | None:
    """Prefer a TYPE unit for ``rel``; never fall back to REPO / path='.'."""
    norm = rel.replace("\\", "/").lstrip("./")
    stem = Path(norm).stem
    best: str | None = None
    for unit in ctx.units:
        if unit.repo != repo or unit.kind != UnitKind.TYPE:
            continue
        up = (unit.path or "").replace("\\", "/").lstrip("./")
        if up == norm or up.endswith("/" + norm) or norm.endswith(up):
            return unit.id
        if stem and simple_name(unit.qualified_name) == stem:
            best = unit.id
    return best


def _collect_draft_map_findings(ctx: AnalysisContext, known: set[str]) -> list[Finding]:
    findings: list[Finding] = []
    # Dedupe by file path so TYPE scan + file rglob cannot emit twins (incl. REPO '.').
    seen_files: set[str] = set()
    for unit in ctx.units_list():
        if unit.kind != UnitKind.TYPE or is_test_path(unit.path):
            continue
        snippet = unit.source_snippet or ""
        if not (_DRAFT_MAP.search(snippet) and re.search(r"new\s+HashMap|Map\s*<", snippet)):
            continue
        if re.search(r"Repository|@Value|@ConfigurationProperties|config\.", snippet, re.IGNORECASE):
            continue
        file_key = _draft_map_file_key(unit.repo, unit.path)
        if file_key in seen_files:
            continue
        seen_files.add(file_key)
        f = try_make_finding(
            id=content_hash(f"slop:draft_map:{unit.id}"),
            goal=AnalysisGoal.SLOP,
            sensor="slop",
            severity=Severity.MEDIUM,
            title=f"Draft in-memory mapping in `{simple_name(unit.qualified_name)}`",
            evidence=(
                f"`{unit.path}` combines draft/TODO markers with constructor-initialized HashMap defaults "
                "without Mongo/config-backed mapping — silent skip risk on unmapped assets; "
                "extract shared config lookup or repository-backed mapping."
            ),
            unit_ids=[unit.id],
            action_hint=SuggestedAction.EXTRACT_SHARED,
            score=0.76,
            metadata={"kind": "draft_in_memory_map", "repo": unit.repo, "path": unit.path},
            known_ids=known,
        )
        if f:
            findings.append(f)

    for repo in ctx.repos:
        for path in _iter_src_main_java(repo):
            rel = str(path.relative_to(repo)).replace("\\", "/")
            if "src/test/" in rel:
                continue
            file_key = _draft_map_file_key(repo.name, rel)
            if file_key in seen_files:
                continue
            text = _read_text(path)
            if not (_DRAFT_MAP.search(text) and re.search(r"new\s+HashMap|Map\s*<", text)):
                continue
            if re.search(r"Repository|@Value|@ConfigurationProperties", text, re.IGNORECASE):
                continue
            uid = _type_unit_for_java_file(ctx, repo.name, rel)
            if not uid:
                continue
            seen_files.add(file_key)
            f = try_make_finding(
                id=content_hash(f"slop:draft_map:file:{file_key}"),
                goal=AnalysisGoal.SLOP,
                sensor="slop",
                severity=Severity.MEDIUM,
                title=f"Draft in-memory mapping in `{path.name}`",
                evidence=(
                    f"`{rel}` combines draft/TODO markers with constructor-initialized HashMap defaults "
                    "without Mongo/config-backed mapping — silent skip risk on unmapped assets; "
                    "extract shared config lookup or repository-backed mapping."
                ),
                unit_ids=[uid],
                action_hint=SuggestedAction.EXTRACT_SHARED,
                score=0.76,
                metadata={"kind": "draft_in_memory_map", "repo": repo.name, "path": rel},
                known_ids=known,
            )
            if f:
                findings.append(f)
    return findings


def _collect_disabled_validation_findings(ctx: AnalysisContext, known: set[str]) -> list[Finding]:
    findings: list[Finding] = []
    seen_files: set[str] = set()

    for unit in ctx.units_list():
        if unit.kind not in {UnitKind.TYPE, UnitKind.FUNCTION} or is_test_path(unit.path):
            continue
        rel = (unit.path or "").replace("\\", "/")
        if not _is_config_validator_path(rel):
            continue
        snippet = unit.source_snippet or ""
        m = _DISABLED_HOOK.search(snippet)
        if not m:
            continue
        file_key = f"{unit.repo}:{rel}"
        if file_key in seen_files:
            continue
        seen_files.add(file_key)
        method = m.group(1)
        f = try_make_finding(
            id=content_hash(f"slop:disabled_validation:{unit.id}"),
            goal=AnalysisGoal.SLOP,
            sensor="slop",
            severity=Severity.MEDIUM,
            title=f"Disabled startup validation `{method}` in {unit.repo}",
            evidence=(
                f"`{rel}` has commented @PostConstruct/@EventListener on `{method}` — "
                "re-enable startup validation or delete the dead hook."
            ),
            unit_ids=[unit.id],
            action_hint=SuggestedAction.SPLIT,
            score=0.79,
            metadata={"kind": "disabled_startup_validation", "method": method, "repo": unit.repo, "path": rel},
            known_ids=known,
        )
        if f:
            findings.append(f)

    for repo in ctx.repos:
        for path in _iter_src_main_java(repo):
            rel = str(path.relative_to(repo)).replace("\\", "/")
            if not _is_config_validator_path(rel):
                continue
            file_key = f"{repo.name}:{rel}"
            if file_key in seen_files:
                continue
            text = _read_text(path)
            m = _DISABLED_HOOK.search(text)
            if not m:
                continue
            uid = _type_unit_for_java_file(ctx, repo.name, rel)
            if not uid:
                continue
            seen_files.add(file_key)
            method = m.group(1)
            f = try_make_finding(
                id=content_hash(f"slop:disabled_validation:file:{repo.name}:{rel}"),
                goal=AnalysisGoal.SLOP,
                sensor="slop",
                severity=Severity.MEDIUM,
                title=f"Disabled startup validation `{method}` in {repo.name}",
                evidence=(
                    f"`{rel}` has commented @PostConstruct/@EventListener on `{method}` — "
                    "re-enable startup validation or delete the dead hook."
                ),
                unit_ids=[uid],
                action_hint=SuggestedAction.SPLIT,
                score=0.79,
                metadata={"kind": "disabled_startup_validation", "method": method, "repo": repo.name, "path": rel},
                known_ids=known,
            )
            if f:
                findings.append(f)
    return findings


class SlopSensor:
    """Workspace-level AI debt: near-duplicate clusters + boilerplate smells."""

    id = "slop"
    goal = AnalysisGoal.SLOP

    def available(self, ctx: AnalysisContext) -> bool:
        return any(u.kind == UnitKind.FUNCTION for u in ctx.units)

    def collect(self, ctx: AnalysisContext) -> list[Finding]:
        known = ctx.known_ids()
        identity_findings = _collect_identity_findings(ctx, known)
        draft_map = _collect_draft_map_findings(ctx, known)
        disabled_val = _collect_disabled_validation_findings(ctx, known)

        funcs = [
            u
            for u in ctx.units_list()
            if u.kind == UnitKind.FUNCTION
            and not _skip_trivial(u)
            and not is_test_path(u.path)
            and _loc(u) >= 8
        ]
        if len(funcs) < 2:
            return identity_findings + draft_map + disabled_val

        fps = {u.id: fingerprints_for_source(u.source_snippet) for u in funcs}
        fps = {k: v for k, v in fps.items() if len(v) >= 2}
        by_id = {u.id: u for u in funcs}

        def _pair_is_slop_signal(a_id: str, b_id: str, score: float) -> bool:
            """True when fingerprint overlap looks like real reimplementation drift."""
            a, b = by_id[a_id], by_id[b_id]
            # Same file: sibling helpers (validatePam* / validatePsn*) share if-chain
            # shape — not agent fork surface to delete.
            if (a.path or "").replace("\\", "/") == (b.path or "").replace("\\", "/"):
                return False
            # Different domain vocabulary → parallel patterns, not copies.
            if domain_token_divergence(a.source_snippet or "", b.source_snippet or "") >= (
                _DOMAIN_DIVERGENCE_SKIP
            ):
                return False
            # Same-repo needs a higher bar than cross-repo echoes (match fingerprint sensor).
            if a.repo == b.repo and score < 0.85:
                return False
            return True

        pairs = candidate_pairs(fps, min_shared=2)
        # Cap before expensive domain-token divergence checks on large workspaces.
        pairs = [(a, b, s) for a, b, s in pairs if s >= 0.70 and a in by_id and b in by_id]
        pairs.sort(key=lambda t: -t[2])
        pairs = pairs[: max(2000, int(getattr(ctx.config, "max_fingerprint_pairs", None) or 80) * 40)]
        pairs = [
            (a, b, s)
            for a, b, s in pairs
            if _pair_is_slop_signal(a, b, s)
        ]

        parent = {uid: uid for uid in fps}

        def find(x: str) -> str:
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        for a, b, _score in pairs:
            ra, rb = find(a), find(b)
            if ra != rb:
                parent[rb] = ra

        clusters: dict[str, list[str]] = defaultdict(list)
        for uid in fps:
            # Only union members that participated in a kept pair stay clustered;
            # isolates with len 1 are dropped by the multi filter below.
            clusters[find(uid)].append(uid)
        multi = [members for members in clusters.values() if len(members) >= 2]
        # Drop clusters that collapsed to a single path (should be rare after pair filter).
        filtered_multi: list[list[str]] = []
        for members in multi:
            paths = {
                (by_id[m].path or "").replace("\\", "/")
                for m in members
                if m in by_id
            }
            if len(paths) < 2:
                continue
            filtered_multi.append(members)
        multi = filtered_multi
        multi.sort(key=len, reverse=True)

        n_funcs = max(1, len(funcs))
        dup_units = sum(len(m) for m in multi)
        slop_ratio = dup_units / n_funcs
        empty_catch = sum(1 for u in funcs if _EMPTY_CATCH.search(u.source_snippet))
        boiler = sum(1 for u in funcs if _BOILER_COMMENTS.search(u.source_snippet))
        cross_clusters = 0
        for members in multi:
            repos = {by_id[m].repo for m in members if m in by_id}
            if len(repos) >= 2:
                cross_clusters += 1

        slop_score = min(
            100.0,
            100.0 * slop_ratio * 0.7
            + min(20.0, empty_catch * 2.0)
            + min(15.0, boiler * 1.5)
            + min(25.0, cross_clusters * 5.0)
            + min(20.0, len(pairs) * 2.0),
        )

        known = ctx.known_ids()
        findings: list[Finding] = []

        top = multi[0] if multi else ([pairs[0][0], pairs[0][1]] if pairs else [funcs[0].id])
        summary = try_make_finding(
            id=content_hash(f"slop:workspace:{slop_score:.1f}:{len(multi)}:{len(pairs)}"),
            goal=self.goal,
            sensor=self.id,
            severity=Severity.HIGH if slop_score >= 40 else Severity.MEDIUM,
            title=f"AI slop score {slop_score:.0f}/100 — {len(multi)} structural duplicate clusters",
            evidence=(
                f"{dup_units}/{n_funcs} functions sit in rename-resistant clusters; "
                f"{len(pairs)} high-Jaccard pairs; {cross_clusters} cross-repo clusters; "
                f"{empty_catch} empty-catch/pass patterns; "
                f"{boiler} generated/TODO markers. "
                f"Prefer extract_shared / delete_duplicate over new agent copies."
            ),
            unit_ids=list(dict.fromkeys(top))[:8],
            action_hint=SuggestedAction.EXTRACT_SHARED,
            score=min(0.95, 0.4 + slop_score / 150.0),
            metrics={
                "slop_score": slop_score,
                "cluster_count": float(len(multi)),
                "pair_count": float(len(pairs)),
                "dup_unit_ratio": slop_ratio,
                "cross_repo_clusters": float(cross_clusters),
                "empty_catch_count": float(empty_catch),
            },
            metadata={"kind": "workspace_slop"},
            known_ids=known,
        )
        if summary:
            findings.append(summary)

        findings.extend(identity_findings)
        findings.extend(draft_map)
        findings.extend(disabled_val)

        for members in multi[:12]:
            units = [by_id[m] for m in members if m in by_id]
            repos = sorted({u.repo for u in units})
            names = Counter(u.qualified_name.split(".")[-1] for u in units)
            label = names.most_common(1)[0][0] if names else "cluster"
            # Slop clusters are shape/fingerprint affinity — never delete_duplicate.
            # True interchangeable copies belong to sim.fingerprint at high Jaccard.
            action = SuggestedAction.EXTRACT_SHARED
            f = try_make_finding(
                id=content_hash("slop:cluster:" + ",".join(sorted(members)[:6])),
                goal=self.goal,
                sensor=self.id,
                severity=Severity.HIGH if len(repos) >= 2 else Severity.MEDIUM,
                title=f"Slop cluster ×{len(members)} around `{label}`",
                evidence=(
                    f"{len(members)} structurally similar functions across "
                    f"{', '.join(repos)} — likely agent reimplementation drift."
                ),
                unit_ids=members[:10],
                action_hint=action,
                score=min(0.93, 0.5 + 0.05 * len(members)),
                metrics={
                    "cluster_size": float(len(members)),
                    "cross_repo": 1.0 if len(repos) >= 2 else 0.0,
                    "slop_score": slop_score,
                },
                metadata={"repos": repos, "kind": "slop_cluster"},
                known_ids=known,
            )
            if f:
                findings.append(f)
        return findings


def slop() -> Sensor:
    return SlopSensor()
